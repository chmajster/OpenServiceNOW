const localeEvent = "opensnow:locale-change";
const localeStorageKey = "opensnow-cmdb-locale";

export function cmdbLocale(): Locale {
  let saved: string | null = null;
  try {
    saved = window.localStorage.getItem(localeStorageKey);
  } catch {
    // Keep the CMDB usable when browser storage is disabled.
  }
  const configured = saved || document.documentElement.lang || navigator.language;
  return configured.toLowerCase().startsWith("en") ? "en" : "pl";
}

export function setCMDBLocale(locale: Locale) {
  try {
    window.localStorage.setItem(localeStorageKey, locale);
  } catch {
    // The active tab still changes language; persistence is best effort.
  }
  document.documentElement.lang = locale;
  window.dispatchEvent(new Event(localeEvent));
}

export function useCMDBLocale() {
  const [locale, setLocale] = useState<Locale>(() => cmdbLocale());
  useEffect(() => {
    const update = () => setLocale(cmdbLocale());
    window.addEventListener(localeEvent, update);
    return () => window.removeEventListener(localeEvent, update);
  }, []);
  return locale;
}

export function cmdbText(key: string, locale = cmdbLocale()) {
  return resources[locale][key] ?? resources.pl[key] ?? key;
}

export function cmdbLabel(key: string, locale = cmdbLocale()): string {
  for (const prefix of ["class.", "status.", "environment.", "relation.", "action.", "state.", "option."]) {
    const label = resources[locale][prefix + key];
    if (label) return label;
  }
  return resources[locale]["asset." + key] ?? cmdbText(key, locale);
}

export function cmdbAttributeLabel(key: string, fallback: string, locale = cmdbLocale()) {
  return resources[locale]["attr." + key] ?? fallback;
}
