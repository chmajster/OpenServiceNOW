CREATE TABLE cmdb_cis (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT UNSIGNED NOT NULL,
 identifier VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 name VARCHAR(160) NOT NULL,
 class VARCHAR(30) NOT NULL,
 status VARCHAR(20) NOT NULL,
 owner_id BIGINT UNSIGNED NOT NULL,
 environment VARCHAR(20) NOT NULL,
 location VARCHAR(160) NOT NULL,
 attributes JSON NOT NULL,
 archived BOOLEAN NOT NULL DEFAULT FALSE,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY ci_tenant_id(tenant_id,id),
 UNIQUE KEY ci_identifier(tenant_id,identifier),
 KEY ci_list(tenant_id,archived,class,id),
 KEY ci_owner(tenant_id,owner_id,id),
 CONSTRAINT ci_class CHECK(class IN('PHYSICAL_SERVER','VM','NETWORK_DEVICE','APPLICATION','SERVICE')),
 CONSTRAINT ci_status CHECK(status IN('PLANNED','ACTIVE','MAINTENANCE','RETIRED')),
 CONSTRAINT ci_environment CHECK(environment IN('DEV','TEST','STAGING','PROD')),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 FOREIGN KEY(owner_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
