CREATE TABLE notification_preferences (
 tenant_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 in_app_enabled BOOLEAN NOT NULL DEFAULT TRUE, smtp_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 assignments BOOLEAN NOT NULL DEFAULT TRUE, replies BOOLEAN NOT NULL DEFAULT TRUE,
 state_changes BOOLEAN NOT NULL DEFAULT TRUE, resolutions BOOLEAN NOT NULL DEFAULT TRUE,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 PRIMARY KEY(tenant_id,user_id),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
