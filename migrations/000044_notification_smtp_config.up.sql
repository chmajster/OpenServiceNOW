CREATE TABLE notification_smtp_config (
 tenant_id BIGINT UNSIGNED PRIMARY KEY, provider_id VARCHAR(100) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT FALSE, host VARCHAR(253) NOT NULL, port INT UNSIGNED NOT NULL,
 tls_mode VARCHAR(20) NOT NULL, username VARCHAR(254) NOT NULL DEFAULT '',
 password_cipher BLOB NULL, from_address VARCHAR(254) NOT NULL,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 CHECK(port BETWEEN 1 AND 65535), CHECK(tls_mode IN ('STARTTLS','TLS','NONE'))
) ENGINE=InnoDB;
