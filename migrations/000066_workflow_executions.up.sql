CREATE TABLE workflow_executions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT UNSIGNED NOT NULL,
 definition_id BIGINT UNSIGNED NOT NULL,
 definition_version BIGINT UNSIGNED NOT NULL,
 request_id BIGINT UNSIGNED NOT NULL,
 requested_item_id BIGINT UNSIGNED NOT NULL,
 requester_id BIGINT UNSIGNED NOT NULL,
 executor_id BIGINT UNSIGNED NOT NULL,
 group_id BIGINT UNSIGNED NOT NULL,
 current_node VARCHAR(48) NOT NULL,
 state VARCHAR(24) NOT NULL DEFAULT 'READY',
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 approved BOOLEAN NOT NULL DEFAULT FALSE,
 error_code VARCHAR(64) NOT NULL DEFAULT '',
 next_check_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 UNIQUE KEY workflow_execution_tenant(tenant_id,id),
 UNIQUE KEY workflow_item(tenant_id,requested_item_id),
 KEY workflow_due(state,next_check_at,id),
 KEY workflow_request(tenant_id,request_id,id),
 FOREIGN KEY(tenant_id,definition_id,definition_version) REFERENCES workflow_versions(tenant_id,definition_id,version),
 FOREIGN KEY(tenant_id,request_id) REFERENCES service_requests(tenant_id,id) ON DELETE CASCADE,
 FOREIGN KEY(tenant_id,requested_item_id) REFERENCES requested_items(tenant_id,id) ON DELETE CASCADE,
 FOREIGN KEY(executor_id) REFERENCES users(id),
 FOREIGN KEY(requester_id) REFERENCES users(id),
 FOREIGN KEY(tenant_id,group_id) REFERENCES `groups`(tenant_id,id) ON DELETE CASCADE,
 CHECK(state IN('READY','WAITING','ERROR','COMPLETED','CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
