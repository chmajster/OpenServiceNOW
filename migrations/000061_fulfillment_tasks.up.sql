CREATE TABLE fulfillment_tasks (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT UNSIGNED NOT NULL,
 request_id BIGINT UNSIGNED NOT NULL,
 requested_item_id BIGINT UNSIGNED NOT NULL,
 number VARCHAR(40) NOT NULL,
 title VARCHAR(200) NOT NULL,
 instructions TEXT NOT NULL,
 required BOOLEAN NOT NULL,
 state VARCHAR(24) NOT NULL DEFAULT 'OPEN',
 result TEXT NOT NULL,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 updated_at DATETIME(6) NOT NULL,
 UNIQUE KEY task_tenant_id(tenant_id,id),
 UNIQUE KEY task_number(tenant_id,number),
 KEY request_tasks(tenant_id,request_id,id),
 FOREIGN KEY(tenant_id,request_id) REFERENCES service_requests(tenant_id,id) ON DELETE CASCADE,
 FOREIGN KEY(tenant_id,requested_item_id) REFERENCES requested_items(tenant_id,id) ON DELETE CASCADE,
 CHECK(state IN('OPEN','IN_PROGRESS','ON_HOLD','COMPLETED','CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
