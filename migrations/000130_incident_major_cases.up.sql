CREATE TABLE incident_major_cases (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT UNSIGNED NOT NULL,
 incident_id BIGINT UNSIGNED NOT NULL,
 status ENUM('CANDIDATE','ACTIVE','REJECTED','DEMOTED','RESTORED') NOT NULL,
 candidate_reason VARCHAR(2000) NOT NULL,
 decision_reason VARCHAR(2000) NOT NULL DEFAULT '',
 nominated_by BIGINT UNSIGNED NOT NULL,
 nominated_at DATETIME(6) NOT NULL,
 decided_by BIGINT UNSIGNED NULL,
 decided_at DATETIME(6) NULL,
 commander_user_id BIGINT UNSIGNED NULL,
 deputy_user_id BIGINT UNSIGNED NULL,
 communications_owner_id BIGINT UNSIGNED NULL,
 bridge_url VARCHAR(2048) NOT NULL DEFAULT '',
 impact_summary VARCHAR(4000) NOT NULL DEFAULT '',
 impact_confidence ENUM('ESTIMATED','CONFIRMED') NOT NULL DEFAULT 'ESTIMATED',
 workaround VARCHAR(4000) NOT NULL DEFAULT '',
 communication_audience ENUM('REPORTERS_AND_AFFECTED','WATCHERS','ALL_LINKED') NOT NULL DEFAULT 'ALL_LINKED',
 update_interval_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 60,
 next_update_at DATETIME(6) NULL,
 detected_at DATETIME(6) NULL,
 restored_at DATETIME(6) NULL,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 UNIQUE KEY incident_major_case_incident(tenant_id,incident_id),
 KEY incident_major_case_queue(tenant_id,status,updated_at,id),
 KEY incident_major_case_reminder(tenant_id,status,next_update_at,id),
 CONSTRAINT incident_major_case_tenant FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 CONSTRAINT incident_major_case_incident_fk FOREIGN KEY(tenant_id,incident_id) REFERENCES incidents(tenant_id,id) ON DELETE CASCADE,
 CONSTRAINT incident_major_case_nominator FOREIGN KEY(tenant_id,nominated_by) REFERENCES tenant_memberships(tenant_id,user_id),
 CONSTRAINT incident_major_case_decider FOREIGN KEY(tenant_id,decided_by) REFERENCES tenant_memberships(tenant_id,user_id),
 CONSTRAINT incident_major_case_commander FOREIGN KEY(tenant_id,commander_user_id) REFERENCES tenant_memberships(tenant_id,user_id),
 CONSTRAINT incident_major_case_deputy FOREIGN KEY(tenant_id,deputy_user_id) REFERENCES tenant_memberships(tenant_id,user_id),
 CONSTRAINT incident_major_case_comms_owner FOREIGN KEY(tenant_id,communications_owner_id) REFERENCES tenant_memberships(tenant_id,user_id),
 CONSTRAINT incident_major_case_interval CHECK(update_interval_minutes BETWEEN 5 AND 1440),
 CONSTRAINT incident_major_case_version CHECK(version>=1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
