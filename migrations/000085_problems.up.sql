CREATE TABLE problems (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT UNSIGNED NOT NULL,
 number VARCHAR(40) NOT NULL,
 reporter_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(160) NOT NULL,
 description TEXT NOT NULL,
 impact VARCHAR(12) NOT NULL,
 symptoms TEXT NOT NULL,
 analysis TEXT NOT NULL,
 root_cause TEXT NOT NULL,
 workaround TEXT NOT NULL,
 solution_plan TEXT NOT NULL,
 verification TEXT NOT NULL,
 known_error BOOLEAN NOT NULL DEFAULT FALSE,
 state VARCHAR(24) NOT NULL DEFAULT 'NEW',
 reason TEXT NOT NULL,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY problem_tenant_id(tenant_id,id),
 UNIQUE KEY problem_number(tenant_id,number),
 KEY problem_backlog(tenant_id,state,id),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 FOREIGN KEY(tenant_id,reporter_id) REFERENCES tenant_memberships(tenant_id,user_id) ON DELETE CASCADE,
 CHECK(state IN('NEW','ASSESS','ROOT_CAUSE','FIX_IN_PROGRESS','RESOLVED','CLOSED','CANCELLED')),
 CHECK(impact IN('HIGH','MEDIUM','LOW')),
 CHECK(NOT known_error OR (CHAR_LENGTH(root_cause)>0 AND CHAR_LENGTH(workaround)>0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
