CREATE TABLE notification_mail_deliveries (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 notification_id BIGINT UNSIGNED NULL, provider_id VARCHAR(100) NOT NULL DEFAULT '',
 status VARCHAR(30) NOT NULL DEFAULT 'QUEUED', attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1, job_id BIGINT UNSIGNED NULL,
 error_code VARCHAR(100) NOT NULL DEFAULT '',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), finished_at DATETIME(6) NULL,
 UNIQUE KEY uq_notification_mail(notification_id), KEY idx_notification_mail(tenant_id,id),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(notification_id) REFERENCES notifications(id) ON DELETE CASCADE,
 FOREIGN KEY(job_id) REFERENCES jobs(id) ON DELETE SET NULL,
 CHECK(status IN ('QUEUED','SENDING','DELIVERED','FAILED','NOT_CONFIGURED','SKIPPED'))
) ENGINE=InnoDB;
