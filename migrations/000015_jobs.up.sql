CREATE TABLE jobs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id BIGINT UNSIGNED NOT NULL,
    job_type VARCHAR(120) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'QUEUED',
    payload JSON NOT NULL,
    result JSON NULL,
    error_message VARCHAR(4000) NULL,
    progress TINYINT UNSIGNED NOT NULL DEFAULT 0,
    attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
    max_attempts INT UNSIGNED NOT NULL DEFAULT 3,
    available_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    lease_owner VARCHAR(190) NULL,
    lease_expires_at DATETIME(6) NULL,
    cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
    idempotency_key VARCHAR(190) NULL,
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    started_at DATETIME(6) NULL,
    finished_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_jobs_idempotency (tenant_id, job_type, idempotency_key),
    KEY idx_jobs_claim (status, available_at, lease_expires_at, id),
    KEY idx_jobs_tenant_id (tenant_id, id),
    KEY idx_jobs_creator (tenant_id, created_by, id),
    CONSTRAINT chk_jobs_status CHECK (status IN ('QUEUED','RUNNING','RETRYING','COMPLETED','FAILED','CANCELLED')),
    CONSTRAINT chk_jobs_progress CHECK (progress <= 100),
    CONSTRAINT chk_jobs_attempts CHECK (max_attempts BETWEEN 1 AND 100 AND attempt_count <= max_attempts),
    CONSTRAINT fk_jobs_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT fk_jobs_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
