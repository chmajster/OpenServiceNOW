CREATE TABLE changes (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, tenant_id BIGINT UNSIGNED NOT NULL,
 number VARCHAR(40) NOT NULL, reporter_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(160) NOT NULL, description TEXT NOT NULL,
 change_type VARCHAR(12) NOT NULL, impact VARCHAR(12) NOT NULL, risk VARCHAR(12) NOT NULL,
 justification TEXT NOT NULL, scope TEXT NOT NULL,
 implementation_plan TEXT NOT NULL, test_plan TEXT NOT NULL, rollback_plan TEXT NOT NULL,
 emergency_reason TEXT NOT NULL, review_result TEXT NOT NULL, review_outcome VARCHAR(12) NOT NULL DEFAULT '',
 planned_start DATETIME(6) NULL, planned_end DATETIME(6) NULL, time_zone VARCHAR(64) NOT NULL,
 actual_start DATETIME(6) NULL, actual_end DATETIME(6) NULL,
 workflow_id BIGINT UNSIGNED NULL, workflow_version BIGINT UNSIGNED NULL,
 template_id BIGINT UNSIGNED NULL, template_version BIGINT UNSIGNED NULL,
 assessment_revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
 approved_revision BIGINT UNSIGNED NULL, evaluated_version BIGINT UNSIGNED NULL,
 approval_state VARCHAR(12) NOT NULL DEFAULT 'NONE', execution_id BIGINT UNSIGNED NULL,
 state VARCHAR(24) NOT NULL DEFAULT 'NEW', reason TEXT NOT NULL,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY change_tenant_id(tenant_id,id), UNIQUE KEY change_number(tenant_id,number),
 KEY change_backlog(tenant_id,state,id), KEY change_calendar(tenant_id,planned_start,planned_end,state),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 FOREIGN KEY(tenant_id,reporter_id) REFERENCES tenant_memberships(tenant_id,user_id) ON DELETE CASCADE,
 FOREIGN KEY(tenant_id,workflow_id,workflow_version) REFERENCES workflow_versions(tenant_id,definition_id,version),
 FOREIGN KEY(tenant_id,template_id,template_version) REFERENCES change_template_versions(tenant_id,template_id,version),
 CHECK(state IN('NEW','ASSESS','AUTHORIZE','SCHEDULED','IMPLEMENT','REVIEW','CLOSED','CANCELLED')),
 CHECK(change_type IN('NORMAL','STANDARD','EMERGENCY')),
 CHECK(impact IN('HIGH','MEDIUM','LOW') AND risk IN('HIGH','MEDIUM','LOW')),
 CHECK(approval_state IN('NONE','PENDING','APPROVED','REJECTED','INVALIDATED')),
 CHECK(review_outcome IN('','SUCCESS','PARTIAL','FAILED')),
 CHECK((planned_start IS NULL AND planned_end IS NULL) OR (planned_start IS NOT NULL AND planned_end>planned_start))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
