CREATE TABLE assets (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT UNSIGNED NOT NULL,
 asset_tag VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 name VARCHAR(160) NOT NULL,
 owner_id BIGINT UNSIGNED NOT NULL,
 serial_number VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
 vendor VARCHAR(160) NOT NULL,
 model VARCHAR(160) NOT NULL,
 location VARCHAR(160) NOT NULL,
 state VARCHAR(20) NOT NULL,
 purchase_date DATE NULL,
 purchase_cost DECIMAL(12,2) NULL,
 currency CHAR(3) NOT NULL,
 warranty_until DATE NULL,
 archived BOOLEAN NOT NULL DEFAULT FALSE,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY asset_tenant_id(tenant_id,id),
 UNIQUE KEY asset_tag_key(tenant_id,asset_tag),
 UNIQUE KEY asset_serial_key(tenant_id,serial_number),
 KEY asset_list(tenant_id,archived,state,id),
 KEY asset_owner(tenant_id,owner_id,id),
 CONSTRAINT asset_state CHECK(state IN('ORDERED','IN_STOCK','IN_USE','IN_REPAIR','RETIRED','DISPOSED')),
 CONSTRAINT asset_cost CHECK(purchase_cost IS NULL OR purchase_cost>=0),
 CONSTRAINT asset_warranty CHECK(purchase_date IS NULL OR warranty_until IS NULL OR warranty_until>=purchase_date),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 FOREIGN KEY(owner_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
