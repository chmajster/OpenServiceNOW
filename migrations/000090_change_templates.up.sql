CREATE TABLE change_templates (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT UNSIGNED NOT NULL, name VARCHAR(160) NOT NULL,
 draft JSON NOT NULL, version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 published_version BIGINT UNSIGNED NULL, withdrawn BOOLEAN NOT NULL DEFAULT FALSE,
 author_id BIGINT UNSIGNED NOT NULL,
 UNIQUE KEY change_template_tenant(tenant_id,id),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 FOREIGN KEY(author_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
