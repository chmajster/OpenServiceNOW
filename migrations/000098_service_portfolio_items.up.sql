CREATE TABLE service_portfolio_items (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT UNSIGNED NOT NULL,
 service_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 name VARCHAR(160) NOT NULL,
 item_type ENUM('BUSINESS_APPLICATION','SERVICE_INSTANCE','TECHNICAL_SERVICE','BUSINESS_SERVICE') NOT NULL,
 description TEXT NOT NULL,
 lifecycle ENUM('DRAFT','PUBLISHED','ACTIVE','RETIRED') NOT NULL DEFAULT 'DRAFT',
 criticality ENUM('CRITICAL','HIGH','MEDIUM','LOW') NOT NULL,
 environment ENUM('DEV','TEST','STAGING','PROD','ALL') NOT NULL,
 scope VARCHAR(200) NOT NULL DEFAULT '',
 business_owner_id BIGINT UNSIGNED NULL,
 technical_owner_id BIGINT UNSIGNED NULL,
 support_group_id BIGINT UNSIGNED NULL,
 org_unit_ref_id BIGINT UNSIGNED NULL,
 department_ref_id BIGINT UNSIGNED NULL,
 cost_center_ref_id BIGINT UNSIGNED NULL,
 location_id BIGINT UNSIGNED NULL,
 ci_id BIGINT UNSIGNED NULL,
 dependency_mode ENUM('NOT_MODELED','ALL','ANY','QUORUM') NOT NULL DEFAULT 'NOT_MODELED',
 dependency_quorum SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 configuration_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 UNIQUE KEY service_portfolio_item_tenant_id(tenant_id,id),
 UNIQUE KEY service_portfolio_item_key(tenant_id,service_key),
 UNIQUE KEY service_portfolio_item_ci(tenant_id,ci_id),
 KEY service_portfolio_item_list(tenant_id,item_type,lifecycle,environment,id),
 KEY service_portfolio_item_owner(tenant_id,business_owner_id,id),
 KEY service_portfolio_item_support(tenant_id,support_group_id,id),
 CONSTRAINT service_portfolio_item_tenant FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 CONSTRAINT service_portfolio_item_business_owner FOREIGN KEY(business_owner_id) REFERENCES users(id),
 CONSTRAINT service_portfolio_item_technical_owner FOREIGN KEY(technical_owner_id) REFERENCES users(id),
 CONSTRAINT service_portfolio_item_support_group FOREIGN KEY(tenant_id,support_group_id) REFERENCES `groups`(tenant_id,id),
 CONSTRAINT service_portfolio_item_org_unit FOREIGN KEY(tenant_id,org_unit_ref_id) REFERENCES service_portfolio_org_refs(tenant_id,id),
 CONSTRAINT service_portfolio_item_department FOREIGN KEY(tenant_id,department_ref_id) REFERENCES service_portfolio_org_refs(tenant_id,id),
 CONSTRAINT service_portfolio_item_cost_center FOREIGN KEY(tenant_id,cost_center_ref_id) REFERENCES service_portfolio_org_refs(tenant_id,id),
 CONSTRAINT service_portfolio_item_location FOREIGN KEY(location_id) REFERENCES asset_catalog_values(id),
 CONSTRAINT service_portfolio_item_ci FOREIGN KEY(tenant_id,ci_id) REFERENCES cmdb_cis(tenant_id,id),
 CONSTRAINT service_portfolio_item_creator FOREIGN KEY(created_by) REFERENCES users(id),
 CONSTRAINT service_portfolio_quorum CHECK((dependency_mode='QUORUM' AND dependency_quorum>0) OR (dependency_mode<>'QUORUM' AND dependency_quorum=0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
