CREATE TABLE incidents (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id BIGINT UNSIGNED NOT NULL,
    number VARCHAR(32) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description MEDIUMTEXT NOT NULL,
    reporter_id BIGINT UNSIGNED NOT NULL,
    affected_user_id BIGINT UNSIGNED NOT NULL,
    category VARCHAR(40) NOT NULL,
    subcategory VARCHAR(40) NOT NULL,
    impact TINYINT UNSIGNED NOT NULL,
    urgency TINYINT UNSIGNED NOT NULL,
    priority TINYINT UNSIGNED NOT NULL,
    priority_override TINYINT UNSIGNED NULL,
    priority_reason VARCHAR(1000) NOT NULL DEFAULT '',
    state VARCHAR(20) NOT NULL DEFAULT 'NEW',
    hold_reason VARCHAR(1000) NOT NULL DEFAULT '',
    resolution_code VARCHAR(40) NOT NULL DEFAULT '',
    resolution_description MEDIUMTEXT NOT NULL,
    cancellation_reason VARCHAR(1000) NOT NULL DEFAULT '',
    version BIGINT UNSIGNED NOT NULL DEFAULT 1,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    started_at DATETIME(6) NULL,
    resolved_at DATETIME(6) NULL,
    closed_at DATETIME(6) NULL,
    cancelled_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_incidents_number (tenant_id, number),
    UNIQUE KEY uq_incidents_tenant_id (tenant_id, id),
    KEY idx_incidents_list (tenant_id, id),
    KEY idx_incidents_state (tenant_id, state, id),
    KEY idx_incidents_priority (tenant_id, priority, id),
    KEY idx_incidents_reporter (tenant_id, reporter_id, id),
    KEY idx_incidents_affected (tenant_id, affected_user_id, id),
    CONSTRAINT chk_incident_levels CHECK (impact BETWEEN 1 AND 3 AND urgency BETWEEN 1 AND 3 AND priority BETWEEN 1 AND 5),
    CONSTRAINT chk_incident_override CHECK (priority_override IS NULL OR priority_override BETWEEN 1 AND 5),
    CONSTRAINT chk_incident_state CHECK (state IN ('NEW','IN_PROGRESS','ON_HOLD','RESOLVED','CLOSED','CANCELLED')),
    CONSTRAINT chk_incident_version CHECK (version >= 1),
    CONSTRAINT fk_incident_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT fk_incident_reporter FOREIGN KEY (tenant_id, reporter_id) REFERENCES tenant_memberships(tenant_id, user_id) ON DELETE CASCADE,
    CONSTRAINT fk_incident_affected FOREIGN KEY (tenant_id, affected_user_id) REFERENCES tenant_memberships(tenant_id, user_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
