CREATE TABLE service_portfolio_offers (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT UNSIGNED NOT NULL,
 offer_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 parent_service_id BIGINT UNSIGNED NOT NULL,
 catalog_item_id BIGINT UNSIGNED NULL,
 name VARCHAR(160) NOT NULL,
 description TEXT NOT NULL,
 availability_conditions VARCHAR(1000) NOT NULL,
 support_model ENUM('STANDARD','EXTENDED','PREMIUM','CUSTOM') NOT NULL,
 obligation_summary VARCHAR(1000) NOT NULL,
 sla_definition_id BIGINT UNSIGNED NULL,
 lifecycle ENUM('DRAFT','ACTIVE','WITHDRAWN') NOT NULL DEFAULT 'DRAFT',
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 UNIQUE KEY service_portfolio_offer_tenant_id(tenant_id,id),
 UNIQUE KEY service_portfolio_offer_key(tenant_id,offer_key),
 UNIQUE KEY service_portfolio_offer_catalog_item(tenant_id,catalog_item_id),
 KEY service_portfolio_offer_parent(tenant_id,parent_service_id,lifecycle,id),
 CONSTRAINT service_portfolio_offer_tenant FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 CONSTRAINT service_portfolio_offer_parent FOREIGN KEY(tenant_id,parent_service_id) REFERENCES service_portfolio_items(tenant_id,id),
 CONSTRAINT service_portfolio_offer_catalog_item FOREIGN KEY(tenant_id,catalog_item_id) REFERENCES catalog_items(tenant_id,id),
 CONSTRAINT service_portfolio_offer_sla FOREIGN KEY(tenant_id,sla_definition_id) REFERENCES sla_definitions(tenant_id,id),
 CONSTRAINT service_portfolio_offer_creator FOREIGN KEY(created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
