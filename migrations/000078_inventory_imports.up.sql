CREATE TABLE inventory_imports (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT UNSIGNED NOT NULL,
 creator_id BIGINT UNSIGNED NOT NULL,
 executor_id BIGINT UNSIGNED NOT NULL,
 target VARCHAR(10) NOT NULL,
 identity_key VARCHAR(30) NOT NULL,
 mapping JSON NOT NULL,
 source_attachment_id BIGINT UNSIGNED NULL,
 file_name VARCHAR(255) NOT NULL,
 state VARCHAR(30) NOT NULL DEFAULT 'QUEUED_PREVIEW',
 error_code VARCHAR(50) NOT NULL DEFAULT '',
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 job_id BIGINT UNSIGNED NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY import_tenant_id(tenant_id,id),
 KEY inventory_import_list(tenant_id,id),
 CONSTRAINT inventory_import_target CHECK(target IN('CI','ASSET')),
 CONSTRAINT inventory_import_state CHECK(state IN('QUEUED_PREVIEW','PREVIEW_READY','QUEUED_APPLY','APPLYING','COMPLETED','PARTIAL','FAILED','CANCELLED')),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 FOREIGN KEY(creator_id) REFERENCES users(id),
 FOREIGN KEY(executor_id) REFERENCES users(id),
 FOREIGN KEY(source_attachment_id) REFERENCES attachments(id) ON DELETE CASCADE,
 FOREIGN KEY(job_id) REFERENCES jobs(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
